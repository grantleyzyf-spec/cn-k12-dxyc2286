def main():
    os.makedirs(OUT, exist_ok=True)
    for book, units in BOOKS.items():
        grade = {"二": 2, "三": 3, "四": 4, "五": 5, "六": 6}[book[0]]
        rec = {"book": book, "grade": grade, "semester": "上", "status": "manual_final",
               "source": {"method": "目录页人工读定（页码=教材印刷页；略读课文名后标（略读））"},
               "units": [{"unit": u, "items": items} for u, items in units]}
        json.dump(rec, open(f"{OUT}/{book}.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        lines = [f"语文（人教版）{book}　单元/课名清单（status=manual_final；页码=教材印刷页）", ""]
        for u, items in units:
            lines.append(u)
            for it in items:
                tag = {"课": "", "板块": "（板块）", "篇": "（篇）"}[it["kind"]]
                lines.append(f"　{it['name']} {it['page']}{tag}")
            lines.append("")
        open(f"{OUT}/{book}.txt", "w", encoding="utf-8").write("\n".join(lines).rstrip() + "\n")
        nk = sum(1 for _, its in units for i in its if i["kind"] == "课")
        npn = sum(1 for _, its in units for i in its if i["kind"] == "篇")
        nb = sum(1 for _, its in units for i in its if i["kind"] == "板块")
        print(f"{book}: {len(units)} 单元 · 课 {nk} · 篇 {npn} · 板块 {nb}")


if __name__ == "__main__":
    main()
