def main():
    qs = json.load(open(QP, encoding="utf-8"))
    ts = json.load(open(TP, encoding="utf-8"))
    n_q = n_r = n_t = 0
    for q in qs:
        qid = q["id"]
        if qid in Q_FIX:
            prompt, answer, expl = Q_FIX[qid]
            if prompt:
                q["prompt"] = q["question"] = prompt
            if answer is not None:
                q["answer"] = answer
            if expl:
                q["explanation"] = expl
            n_q += 1
        if qid in Q_REWRITE:
            rec = Q_REWRITE[qid]
            q["prompt"] = q["question"] = rec["prompt"]
            q["answer"] = rec["answer"]
            q["options"] = rec["options"]
            q["explanation"] = rec["explanation"]
            n_r += 1
    for t in ts:
        if t["id"] in TOPIC_FIX:
            t.update(TOPIC_FIX[t["id"]])
            n_t += 1
    print(f"题面修 {n_q} 条 · 整题重写 {n_r} 条 · 知识点课标修 {n_t} 条")
    if not WRITE:
        print("（未加 --write，不落盘）")
        return
    json.dump(qs, open(QP, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    open(QP, "a").write("\n")
    json.dump(ts, open(TP, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    open(TP, "a").write("\n")
    print("✅ 已写入")


if __name__ == "__main__":
    main()
