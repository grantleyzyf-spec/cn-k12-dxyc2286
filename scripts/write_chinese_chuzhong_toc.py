def main():
    os.makedirs(OUT, exist_ok=True)
    for book, (method, units) in BOOKS.items():
        grade = {"七": 7, "八": 8, "九": 9}[book[0]]
        rec = {"book": book, "grade": grade, "semester": "上", "status": "manual_final",
               "source": {"method": method + "（页码=教材印刷页；自读课文名后标（自读））"},
               "units": [{"unit": u, "items": items} for u, items in units]}
        json.dump(rec, open(f"{OUT}/{book}.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        lines = [f"语文（人教版）{book}　单元/课名清单（status=manual_final；页码=教材印刷页）", ""]
        for u, items in units:
            lines.append(u)
            for it in items:
                tag = {"课": "", "板块": "（板块）", "篇": "（篇）"}[it["kind"]]
                lines.append(f"　{it['name']} {it['page']}{tag}")
            lines.append("")
        open(f"{OUT}/{book}.txt", "w", encoding="utf-8").write("\n".join(lines).rstrip() + "\n")
        n_ke = sum(1 for _, its in units for i in its if i["kind"] == "课")
        n_pian = sum(1 for _, its in units for i in its if i["kind"] == "篇")
        n_b = sum(1 for _, its in units for i in its if i["kind"] == "板块")
        print(f"{book}: {len(units)} 单元 · 课 {n_ke} · 篇(古诗/子篇) {n_pian} · 板块 {n_b}")


if __name__ == "__main__":
    main()
