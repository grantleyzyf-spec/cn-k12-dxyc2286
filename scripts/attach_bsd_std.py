def norm(s):
    return re.sub(r"\s+", "", s or "")


def build_pool(pool, txt, tag):
    raw = open(txt, encoding="utf-8", errors="ignore").read()
    N = norm(raw)
    lines = [norm(l) for l in raw.split("\n")]
    bad = [sid for sid, _, q in pool if norm(q) not in N]
    if bad:
        raise SystemExit(f"[{tag}] 引文未在课标原文逐字命中：{bad}")
    table = {}
    for sid, dom, q in pool:
        head = norm(q)[:12]
        table[sid] = {"domain": dom, "quote": q,
                      "line": next((i + 1 for i, l in enumerate(lines) if head and head in l), 0)}
    print(f"[{tag}] 引文库 {len(pool)} 条，全部逐字回表命中 ✅")
    return table


def assign(topic, rules, table, default):
    key = topic["name"] + " " + topic.get("chapter", "")
    for pat, sid in rules:
        if re.search(pat, key) and table[sid]["domain"] == topic["domain"]:
            return sid, "partial"
    return default[topic["domain"]], "inferred"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="data/math-bsd")
    ap.add_argument("--preview", choices=["初中", "高中"], help="只预览某学段骨架，不写盘")
    ap.add_argument("--skeleton", help="预览用骨架文件路径")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()

    T1 = build_pool(POOL1, TXT_C, "义务教育·第一学段")
    T4 = build_pool(POOL4, TXT_C, "义务教育·第四学段")
    TH = build_pool(POOLH, TXT_H, "高中")
    TABLE = {"1": T1, "4": T4, "H": TH}

    if a.preview:
        sk = a.skeleton or f"{a.root}/_skeleton_{a.preview}.json"
        topics = json.load(open(sk, encoding="utf-8"))
        topics = topics["topics"] if isinstance(topics, dict) else topics
        print(f"预览 {sk}：{len(topics)} 点")
    else:
        topics = json.load(open(f"{a.root}/topics.json", encoding="utf-8"))

    cnt = Counter()
    for t in topics:
        g = t.get("grade") or 0
        if g in (1, 2):
            sid, conf = assign(t, RULES1, T1, DEFAULT1)
            std_id = f"mbs-2022:{sid}"
        elif 7 <= g <= 9:
            sid, conf = assign(t, RULES4, T4, DEFAULT4)
            std_id = f"mbs-2022:{sid}"
        elif g >= 10:
            sid, conf = assign(t, RULESH, TH, DEFAULTH)
            std_id = f"mbs-2017:{sid}"
        else:                      # 3–6 年级不在本脚本口径内（小学中高段归并行会话）
            cnt["跳过·小学中高段"] += 1
            continue
        seg = sid.split(".")[0]
        q = TABLE[seg][sid]
        t["standards"] = [{"id": std_id, "confidence": conf, "quote": q["quote"], "sourceLine": q["line"]}]
        t["curriculumRef"] = std_id
        cnt[conf] += 1
        cnt["std:" + sid] += 1

    for t in topics:
        if not t.get("prerequisites") and not t.get("root_reason"):
            head = t.get("chapter", "").split(" ", 1)
            t["root_reason"] = (f"起始知识点：《{head[0]}》{head[1] if len(head) > 1 else ''}的第 1 课时，"
                                "本单元无更早的校内先修；跨册衔接以 soft 边表示")

    print("confidence:", {k: v for k, v in cnt.items() if k in ("partial", "inferred", "跳过·小学中高段")})
    reuse = {k[4:]: v for k, v in cnt.items() if k.startswith("std:")}
    print(f"引文复用 {len(reuse)} 条；单条最大复用 {max(reuse.values()) if reuse else 0}")
    if a.write:
        json.dump(topics, open(f"{a.root}/topics.json", "w", encoding="utf-8"), ensure_ascii=False, indent=2)
        open(f"{a.root}/topics.json", "a", encoding="utf-8").write("\n")
        print("written", f"{a.root}/topics.json")


if __name__ == "__main__":
    main()
