def load_std_items():
    s = open(STD_TXT, encoding='utf-8', errors='ignore').read()
    items = {}
    for m in re.finditer(r'^\s*(\d\.\d\.\d)\s*(.{6,200}?)\s*$', s, re.M):
        iid, body = m.group(1), m.group(2)
        if iid not in items and len(re.findall(r'[\u4e00-\u9fa5]', body)) >= 8:
            items[iid] = re.sub(r'\s+', '', body)
    return items


