def main():
    qs = json.load(open(QP, encoding="utf-8"))
    idx = {q["id"]: q for q in qs}
    miss, done = [], 0
    for qid, spec in FIX.items():
        old, new = spec[0], spec[1]
        extra = spec[2] if len(spec) > 2 else {}
        q = idx.get(qid)
        if q is None:
            miss.append((qid, "不存在"))
            continue
        prompt = q.get("prompt", "")
        if old not in prompt:
            miss.append((qid, "旧片段未命中"))
            continue
        if prompt.count(old) != 1:
            miss.append((qid, f"出现 {prompt.count(old)} 次"))
            continue
        q["prompt"] = prompt.replace(old, new)
        q["question"] = q["prompt"]
        for k, v in extra.items():
            q[k] = v
        done += 1
    print(f"可修 {done} / {len(FIX)}；问题 {miss}")
    if not WRITE:
        print("（未加 --write，不落盘）")
        return
    json.dump(qs, open(QP, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    open(QP, "a").write("\n")
    print("✅ 已写入")


if __name__ == "__main__":
    main()
