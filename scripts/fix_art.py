def main():
    n_diff = n_root = n_type = n_dom = 0
    for t in topics:
        if t.get("difficulty") in ("easy", "medium"):
            t["difficulty"] = "basic"
        if t.get("difficulty") not in ("basic", "standard", "hard"):
            t.pop("difficulty", None)
        if not t.get("prerequisites"):
            if t["id"] in ROOT_REASON and t.get("root_reason") != ROOT_REASON[t["id"]]:
                t["root_reason"] = ROOT_REASON[t["id"]]
                n_root += 1
        want = "procedural" if t["name"] in PROC else ("application" if t["name"] in APPR else None)
        if want and t.get("type") != want:
            t["type"] = want
            n_type += 1
        if t["name"] in DOMAIN_FIX and t.get("domain") != DOMAIN_FIX[t["name"]]:
            t["domain"] = DOMAIN_FIX[t["name"]]
            n_dom += 1

    questions = []
    tmap = {t["id"]: t for t in topics}
    for qid, tid, prompt, opts, ans, diff, expl in Q:
        assert tid in tmap, tid
        labels = [o[0] for o in opts]
        assert ans in labels and len(opts) == 4, (qid, labels, ans)
        questions.append({
            "id": qid, "topicId": tid, "prompt": prompt, "question": prompt,
            "options": [{"label": l, "text": x} for l, x in opts],
            "answer": ans, "type": "choice", "difficulty": diff, "explanation": expl,
        })
        t = tmap[tid]
        t["diagnostic_question"] = {"question": prompt, "answer": ans}

    # 覆盖前先把旧题里可能存在的其他字段清掉（本学科题库整体重建）
    assert len(questions) == 26 and {q["topicId"] for q in questions} == set(tmap), "题库未覆盖全部知识点"

    # ---------- 5) 课标重挂 ----------
    n_std = 0
    for t in topics:
        tid = t["id"]
        if tid in STD_MAP:
            key, conf = STD_MAP[tid]
            sid = "art-2022:" + key
            quote = ART2022[key]
        elif tid in STD_HIGH:
            sid, conf = STD_HIGH[tid]
            quote = (t.get("standards") or [{}])[0].get("quote")
            if not quote:
                raise SystemExit(f"{tid} 缺高中课标 quote，先人工核对原文再跑")
        else:
            continue
        new = [{"id": sid, "quote": quote, "confidence": conf}]
        if t.get("standards") != new:
            n_std += 1
        t["standards"] = new
        t["curriculumRef"] = sid

    # ---------- 6) sourceLine（quote 在底本中的行号；义教 = OCR 底本，高中 = 解码 TXT） ----------
    yj_txt, gz_txt = SRC.yijiao_text(), SRC.read_source(SRC.GAOZHONG)
    n_line = n_noline = 0
    for t in topics:
        for s in t["standards"]:
            src = gz_txt if s["id"].startswith("art-2017") else yj_txt
            line = SRC.find_line(src, s.get("quote"), use_ocr_fix=not s["id"].startswith("art-2017"))
            if line and s.get("sourceLine") != line:
                s["sourceLine"] = line
                n_line += 1
            if not line:
                s.setdefault("sourceLine", 0)
                n_noline += 1

    from collections import Counter
    print(f"根节点补 reason {n_root} | 类型校正 {n_type} | 领域校正 {n_dom} | 课标重挂 {n_std}")
    print(f"sourceLine 写入 {n_line} | 未定位 {n_noline}")
    print("置信度:", Counter(s["confidence"] for t in topics for s in t["standards"]))
    print("课标条目去重:", len({s["id"] for t in topics for s in t["standards"]}))

    print("难度:", Counter(q["difficulty"] for q in questions))
    print("答案分布:", {k: sum(1 for q in questions if q["answer"] == k) for k in "ABCD"})
    print("知识点类型:", Counter(t["type"] for t in topics))
    print("领域:", Counter(t["domain"] for t in topics))
    print("根节点无 reason:", [t["id"] for t in topics if not t.get("prerequisites") and not t.get("root_reason")])
    print("题干最短:", min(len(q["prompt"]) for q in questions), "字")

    if WRITE:
        json.dump(topics, open(tp, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
        json.dump(questions, open(qp, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
        print("WRITTEN", tp, qp)
    else:
        print("dry-run，加 --write 落盘")


if __name__ == "__main__":
    main()
