def main():
    write = "--write" in sys.argv
    n = 0
    for (book, paper, no), rules in FIX.items():
        p = os.path.join(L, book, paper + ".json")
        d = json.load(open(p, encoding="utf-8"))
        md = d["markdown"]
        blocks = re.split(r"(?=\n#{3,4} 第 \d+ 题)", "\n" + md)
        touched = False
        for i, b in enumerate(blocks):
            m = re.match(r"\n#{3,4} 第 (\d+) 题", b)
            if not m or int(m.group(1)) != no:
                continue
            for pat, rep in rules:
                new_b, k = re.subn(pat, rep, b)
                if k:
                    n += k
                    touched = True
                    b = new_b
                    print(f"  ✓ {book}/{paper} #{no}: {pat[:26]}…")
                else:
                    print(f"  ⚠ {book}/{paper} #{no}: 未命中 {pat[:26]}…")
            blocks[i] = b
        if touched:
            d["markdown"] = "".join(blocks).lstrip("\n")
            if write:
                json.dump(d, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("替换", n, "处", "" if write else "（干跑，加 --write 落盘）")


if __name__ == "__main__":
    main()
